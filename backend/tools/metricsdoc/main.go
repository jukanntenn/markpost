// Command metricsdoc regenerates the metrics inventory documentation
// (docs/metrics.md, docs/metrics.zh.md, and their .i18n.yaml record) from the
// instrument declarations in the source tree.
//
// It is the single source of the inventory: business instruments are parsed
// from internal/observability/metrics.go and internal/middleware/active_requests.go,
// the adapter mapping from cmd/server/metrics_adapters.go, and service-layer
// call sites by scanning call expressions of the adapter methods. Instruments
// with zero call sites are marked dead — the visibility the generated doc
// exists for. The otelgin and contrib-runtime sections are version-anchored:
// the versions are read from go.mod and must exist in the verified tables
// below, so a dependency bump without re-verification fails `go generate`
// instead of silently documenting stale facts.
//
// Output is deterministic and network-free. The optional -live flag reconciles
// the inventory against a VictoriaMetrics /api/v1/metadata endpoint as a
// supplementary column; it is never used by the gates.
//
// Regenerate with `go generate ./...` from backend/ (the directive lives in
// internal/observability/gen.go).
package main

