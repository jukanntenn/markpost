// --- live reconciliation ---------------------------------------------------

func fetchLiveMetadata(ctx context.Context, base string) (map[string]bool, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, base+"/api/v1/metadata", nil)
	if err != nil {
		return nil, err
	}
	client := &http.Client{Timeout: 15 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s/api/v1/metadata: %s", base, resp.Status)
	}
	var payload struct {
		Status string                     `json:"status"`
		Data   map[string]json.RawMessage `json:"data"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&payload); err != nil {
		return nil, err
	}
	set := make(map[string]bool, len(payload.Data))
	for name := range payload.Data {
		set[name] = true
	}
	return set, nil
}

