func render(st site, t texts, chinese bool) string {
	var b strings.Builder
	b.WriteString(generatedMarker + "\n\n")
	b.WriteString("# " + t.title + "\n\n")
	if chinese {
		b.WriteString("[English](metrics.md) | 中文\n\n")
	}
	renderBody(&b, st, t)
	return b.String()
}

func renderBody(b *strings.Builder, st site, t texts) {
	for _, p := range t.intro {
		b.WriteString(p + "\n\n")
	}

	b.WriteString(t.business + "\n\n")
	writeTable(b, t.cols[:], rows(st, "business", t, false))

	b.WriteString(t.mwTitle + "\n\n")
	writeTable(b, t.cols[:], rows(st, "middleware", t, false))

	b.WriteString(t.otelginTitle + " (otelgin " + st.otelginVersion + ")\n\n")
	for _, p := range t.otelginIntro {
		b.WriteString(p + "\n\n")
	}
	writeAutoTable(b, t, verifiedOtelgin[st.otelginVersion])

	b.WriteString(t.runtimeTitle + " (contrib/instrumentation/runtime " + st.runtimeVersion + ")\n\n")
	for _, p := range t.runtimeIntro {
		b.WriteString(p + "\n\n")
	}
	writeAutoTable(b, t, verifiedRuntime[st.runtimeVersion])

	b.WriteString("## " + t.liveTitle + "\n\n")
	if st.live == nil {
		b.WriteString(t.liveNote + "\n\n")
	} else {
		writeTable(b, append(t.cols[:], "VictoriaMetrics"), rows(st, "business", t, true))
		writeTable(b, append(t.cols[:], "VictoriaMetrics"), rows(st, "middleware", t, true))
		writeAutoLiveTable(b, st, verifiedOtelgin[st.otelginVersion])
		writeAutoLiveTable(b, st, verifiedRuntime[st.runtimeVersion])
	}
	for _, p := range t.regen {
		b.WriteString(p + "\n")
	}
}

func rows(st site, section string, t texts, withLive bool) [][]string {
	var out [][]string
	for _, ins := range st.instruments {
		if ins.Section != section {
			continue
		}
		attrs := "—"
		if len(ins.Attributes) > 0 {
			attrs = "`" + strings.Join(ins.Attributes, "`, `") + "`"
		}
		unit := "—"
		if ins.Unit != "" {
			unit = "`" + ins.Unit + "`"
		}
		calls := t.dead
		if len(ins.CallSites) > 0 {
			calls = strings.Join(codeRefs(ins.CallSites), ", ")
		}
		desc := ins.Description
		if ins.Buckets != "" {
			desc += " Buckets: " + ins.Buckets + " (s)."
		}
		adapter := "—"
		if ins.Adapter != "" {
			adapter = "`" + ins.Adapter + "`"
		}
		row := []string{
			"`" + ins.Name + "`",
			ins.Kind,
			unit,
			desc,
			attrs,
			adapter,
			calls,
		}
		if withLive {
			row = append(row, liveCell(st, ins.Name))
		}
		out = append(out, row)
	}
	return out
}

// codeRefs renders call-site links with basename labels; the full repo
// relative path stays in the link target.
func codeRefs(sites []string) []string {
	out := make([]string, len(sites))
	for i, s := range sites {
		file, line, _ := strings.Cut(s, ":")
		out[i] = "[" + filepath.Base(file) + ":" + line + "](../" + file + ")"
	}
	return out
}

func liveCell(st site, name string) string {
	switch {
	case st.live == nil:
		return "—"
	case st.live[name]:
		return "present"
	default:
		return "absent"
	}
}

// writeTable emits a GitHub-flavored table padded to aligned columns — the
// exact layout the repository's prettier hook produces — so generated output
// and the formatter agree byte for byte and the drift gate never fights
// prettier.
func writeTable(b *strings.Builder, cols []string, rows [][]string) {
	widths := make([]int, len(cols))
	for i, c := range cols {
		widths[i] = mdWidth(c)
	}
	for _, row := range rows {
		for i, cell := range row {
			if i < len(widths) && mdWidth(cell) > widths[i] {
				widths[i] = mdWidth(cell)
			}
		}
	}
	writePaddedRow(b, cols, widths)
	b.WriteString("| " + strings.Join(dashes(widths), " | ") + " |\n")
	for _, row := range rows {
		writePaddedRow(b, row, widths)
	}
	b.WriteString("\n")
}

func writePaddedRow(b *strings.Builder, cells []string, widths []int) {
	b.WriteString("|")
	for i, cell := range cells {
		if i >= len(widths) {
			b.WriteString(" " + cell + " |")
			continue
		}
		b.WriteString(" " + cell + strings.Repeat(" ", widths[i]-mdWidth(cell)) + " |")
	}
	b.WriteString("\n")
}

func dashes(widths []int) []string {
	out := make([]string, len(widths))
	for i, w := range widths {
		if w < 3 {
			w = 3
		}
		out[i] = strings.Repeat("-", w)
	}
	return out
}

// mdWidth measures display width the way prettier does: East Asian wide and
// fullwidth runes count 2, everything else (including the em dash) counts 1.
func mdWidth(s string) int {
	w := 0
	for _, r := range s {
		wide := unicode.Is(unicode.Han, r) ||
			unicode.Is(unicode.Hangul, r) ||
			unicode.Is(unicode.Hiragana, r) ||
			unicode.Is(unicode.Katakana, r) ||
			(r >= 0xFF00 && r <= 0xFF60) || // fullwidth forms
			(r >= 0xFFE0 && r <= 0xFFE6)
		if wide {
			w += 2
		} else {
			w++
		}
	}
	return w
}

func writeAutoTable(b *strings.Builder, t texts, autos []autoInstrument) {
	cols := t.autoCols[:]
	var rows [][]string
	for _, a := range autos {
		attrs := "—"
		if len(a.Attributes) > 0 {
			attrs = strings.Join(a.Attributes, ", ")
		}
		if a.AttrNote != "" {
			if attrs == "—" {
				attrs = a.AttrNote
			} else {
				attrs += "; " + a.AttrNote
			}
		}
		unit := "—"
		if a.Unit != "" {
			unit = "`" + a.Unit + "`"
		}
		rows = append(rows, []string{"`" + a.Name + "`", a.Kind, unit, attrs, noteOr(a.Note)})
	}
	writeTable(b, cols, rows)
}

func writeAutoLiveTable(b *strings.Builder, st site, autos []autoInstrument) {
	b.WriteString("| Name | VictoriaMetrics |\n")
	b.WriteString("| --- | --- |\n")
	for _, a := range autos {
		b.WriteString("| `" + a.Name + "` | " + liveCell(st, a.Name) + " |\n")
	}
	b.WriteString("\n")
}

func noteOr(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

// sortSites orders file:line refs by file, then by numeric line.
func sortSites(sites []string) []string {
	sort.Slice(sites, func(i, j int) bool {
		fi, li, _ := strings.Cut(sites[i], ":")
		fj, lj, _ := strings.Cut(sites[j], ":")
		if fi != fj {
			return fi < fj
		}
		ni, _ := strconv.Atoi(li)
		nj, _ := strconv.Atoi(lj)
		return ni < nj
	})
	return sites
}

// i18nRecord writes the pairing consistency record with git blob hashes of
// both generated sides, matching `hdsh pairing record docs/metrics.md`.
func i18nRecord() string {
	return i18nHeader +
		"metrics.md: " + blobHash(renderedEN) + "\n" +
		"metrics.zh.md: " + blobHash(renderedZH) + "\n"
}

const i18nHeader = `# Bilingual-pair consistency record (docs/i18n/README.md): the git blob
# hash of each side as of the last confirmed-consistent state. Both
# languages carry equal authority;
# after editing either side, bring the other along and re-record with:
#   hdsh pairing record docs/metrics.md
`

// renderedEN/renderedZH hold the exact bytes whose blob hashes the record
// carries; they are set in main before the record is written.
var renderedEN, renderedZH string

// blobHash computes the git blob hash (sha1 of "blob <size>\0<content>") so
// the record matches git hash-object without shelling out.
func blobHash(content string) string {
	h := sha1.New()
	_, _ = fmt.Fprintf(h, "blob %d\x00", len(content))
	h.Write([]byte(content))
	return fmt.Sprintf("%x", h.Sum(nil))
}
