// generatedMarker is the Go-community generated-file marker; it must stay the
// first line of every emitted document.
const generatedMarker = "<!-- Code generated by backend/tools/metricsdoc. DO NOT EDIT. -->"

func main() {
	live := flag.String("live", "", "optional VictoriaMetrics base URL; reconciles the inventory against /api/v1/metadata as a supplementary column (never used by gates)")
	flag.Parse()

	backendDir, err := moduleRoot()
	if err != nil {
		fail("locate module root: %v", err)
	}

	instrs, otelginVer, runtimeVer, err := collect(backendDir)
	if err != nil {
		fail("%v", err)
	}

	var liveSet map[string]bool
	if *live != "" {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		liveSet, err = fetchLiveMetadata(ctx, strings.TrimRight(*live, "/"))
		if err != nil {
			fail("--live: %v", err)
		}
	}

	st := site{instruments: instrs, live: liveSet, otelginVersion: otelginVer, runtimeVersion: runtimeVer}
	renderedEN = render(st, textsEN, false)
	renderedZH = render(st, textsZH, true)

	docsDir := filepath.Join(filepath.Dir(backendDir), "docs")
	for name, content := range map[string]string{
		"metrics.md":        renderedEN,
		"metrics.zh.md":     renderedZH,
		"metrics.i18n.yaml": i18nRecord(),
	} {
		if err := os.WriteFile(filepath.Join(docsDir, name), []byte(content), 0o644); err != nil {
			fail("write %s: %v", name, err)
		}
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "metricsdoc: "+format+"\n", args...)
	os.Exit(1)
}

// moduleRoot walks up from the working directory to the directory holding the
// markpost go.mod, so the tool behaves identically under go generate (cwd =
// the directive's package dir) and a direct go run from backend/.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil && strings.HasPrefix(string(data), "module markpost") {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no markpost go.mod found above %s", dir)
		}
		dir = parent
	}
}

// --- instrument collection -------------------------------------------------

type instrument struct {
	Name        string
	Kind        string // counter | up-down counter | histogram
	Unit        string
	Description string
	Buckets     string
	Adapter     string   // "postMetrics.IncPostsCreated" or ""
	Attributes  []string // attribute keys set by the adapter, e.g. error_category
	CallSites   []string // repo-relative file:line
	Source      string   // repo-relative file:line of the declaration
	Section     string   // "business" | "middleware"
}

var kindByConstructor = map[string]string{
	"Int64Counter":       "counter",
	"Int64UpDownCounter": "up-down counter",
	"Float64Histogram":   "histogram",
}

func collect(backendDir string) ([]instrument, string, string, error) {
	fset := token.NewFileSet()

	metricsFile := filepath.Join(backendDir, "internal/observability/metrics.go")
	middlewareFile := filepath.Join(backendDir, "internal/middleware/active_requests.go")
	adapterFile := filepath.Join(backendDir, "cmd/server/metrics_adapters.go")

	mTree, err := parser.ParseFile(fset, metricsFile, nil, 0)
	if err != nil {
		return nil, "", "", err
	}
	wTree, err := parser.ParseFile(fset, middlewareFile, nil, 0)
	if err != nil {
		return nil, "", "", err
	}
	aTree, err := parser.ParseFile(fset, adapterFile, nil, 0)
	if err != nil {
		return nil, "", "", err
	}

	buckets := bucketVars(mTree)
	byLocal, err := newMetricsInstruments(mTree, buckets)
	if err != nil {
		return nil, "", "", err
	}
	localToField := returnFieldMap(mTree)

	// Struct fields in declaration order, mapped to their local variables.
	fieldToLocal := map[string]string{}
	for local, field := range localToField {
		fieldToLocal[field] = local
	}
	fields := metricsStructFields(mTree)

	adapters := parseAdapters(aTree)

	var instrs []instrument
	for _, f := range fields {
		local, ok := fieldToLocal[f.name]
		if !ok {
			return nil, "", "", fmt.Errorf("metrics.go: Metrics field %s is not returned from NewMetrics", f.name)
		}
		ins, ok := byLocal[local]
		if !ok {
			return nil, "", "", fmt.Errorf("metrics.go: Metrics field %s has no resolved instrument", f.name)
		}
		if m, ok := adapters[f.name]; ok {
			ins.Adapter = m.label
			ins.Attributes = m.attributes
		}
		ins.Section = "business"
		ins.Source = relToRepo(backendDir, metricsFile) + ":" + strconv.Itoa(fset.Position(f.pos).Line)
		instrs = append(instrs, ins)
	}

	mwInstr, mwVar, mwPos, err := middlewareInstrument(wTree)
	if err != nil {
		return nil, "", "", err
	}
	mwInstr.Section = "middleware"
	mwInstr.Source = relToRepo(backendDir, middlewareFile) + ":" + strconv.Itoa(fset.Position(mwPos).Line)
	mwInstr.CallSites = varCallSites(fset, wTree, mwVar, relToRepo(backendDir, middlewareFile))
	instrs = append(instrs, mwInstr)

	// Service-layer call sites: scan every non-test file under internal/ for
	// call expressions of the adapter method names (the distinctive interface
	// methods, not the generic .Add/.Record).
	byMethod := map[string]*instrument{}
	for i := range instrs {
		if instrs[i].Adapter != "" {
			byMethod[methodSuffix(instrs[i].Adapter)] = &instrs[i]
		}
	}
	if err := scanCallSites(backendDir, byMethod); err != nil {
		return nil, "", "", err
	}
	for i := range instrs {
		instrs[i].CallSites = sortSites(instrs[i].CallSites)
	}

	otelginVer, runtimeVer, err := readDepVersions(backendDir)
	if err != nil {
		return nil, "", "", err
	}
	return instrs, otelginVer, runtimeVer, nil
}

func methodSuffix(adapter string) string {
	return adapter[strings.LastIndex(adapter, ".")+1:]
}

func relToRepo(backendDir, path string) string {
	rel, err := filepath.Rel(filepath.Dir(backendDir), path)
	if err != nil {
		return path
	}
	return filepath.ToSlash(rel)
}

// bucketVars resolves package-level float composite literals referenced by
// WithExplicitBucketBoundaries.
func bucketVars(f *ast.File) map[string][]float64 {
	out := map[string][]float64{}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || len(vs.Values) != 1 {
				continue
			}
			cl, ok := vs.Values[0].(*ast.CompositeLit)
			if !ok {
				continue
			}
			vals, ok := floatList(cl)
			if ok {
				for _, name := range vs.Names {
					out[name.Name] = vals
				}
			}
		}
	}
	return out
}

func floatList(cl *ast.CompositeLit) ([]float64, bool) {
	vals := make([]float64, 0, len(cl.Elts))
	for _, elt := range cl.Elts {
		bl, ok := elt.(*ast.BasicLit)
		if !ok || bl.Kind != token.FLOAT && bl.Kind != token.INT {
			return nil, false
		}
		v, err := strconv.ParseFloat(bl.Value, 64)
		if err != nil {
			return nil, false
		}
		vals = append(vals, v)
	}
	return vals, true
}

type structField struct {
	name string
	pos  token.Pos
}

func metricsStructFields(f *ast.File) []structField {
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "Metrics" {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}
			var fields []structField
			for _, fld := range st.Fields.List {
				for _, n := range fld.Names {
					fields = append(fields, structField{name: n.Name, pos: n.Pos()})
				}
			}
			return fields
		}
	}
	return nil
}

// newMetricsInstruments finds every `x, _ := m.<Constructor>("name", opts...)`
// assignment inside NewMetrics, keyed by the local variable name.
func newMetricsInstruments(f *ast.File, buckets map[string][]float64) (map[string]instrument, error) {
	out := map[string]instrument{}
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "NewMetrics" {
			continue
		}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			assign, ok := n.(*ast.AssignStmt)
			if !ok || len(assign.Lhs) != 2 || len(assign.Rhs) != 1 {
				return true
			}
			call, ok := assign.Rhs[0].(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			kind, known := kindByConstructor[sel.Sel.Name]
			if !known || len(call.Args) == 0 {
				return true
			}
			name, ok := stringLiteral(call.Args[0])
			if !ok {
				return true
			}
			local, ok := assign.Lhs[0].(*ast.Ident)
			if !ok {
				return true
			}
			out[local.Name] = parseOptions(call.Args[1:], buckets, instrument{Name: name, Kind: kind})
			return true
		})
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no instruments found in NewMetrics")
	}
	return out, nil
}

func parseOptions(args []ast.Expr, buckets map[string][]float64, ins instrument) instrument {
	for _, arg := range args {
		opt, ok := arg.(*ast.CallExpr)
		if !ok || len(opt.Args) == 0 {
			continue
		}
		osel, ok := opt.Fun.(*ast.SelectorExpr)
		if !ok {
			continue
		}
		switch osel.Sel.Name {
		case "WithDescription":
			if d, ok := stringLiteral(opt.Args[0]); ok {
				ins.Description = d
			}
		case "WithUnit":
			if u, ok := stringLiteral(opt.Args[0]); ok {
				ins.Unit = u
			}
		case "WithExplicitBucketBoundaries":
			var vals []float64
			for _, b := range opt.Args {
				switch v := b.(type) {
				case *ast.Ident:
					vals = append(vals, buckets[v.Name]...)
				case *ast.BasicLit:
					if f, err := strconv.ParseFloat(v.Value, 64); err == nil {
						vals = append(vals, f)
					}
				}
			}
			parts := make([]string, len(vals))
			for i, v := range vals {
				parts[i] = strconv.FormatFloat(v, 'g', -1, 64)
			}
			ins.Buckets = strings.Join(parts, ", ")
		}
	}
	return ins
}

// returnFieldMap ties each local variable to its Metrics struct field via the
// `return &Metrics{Field: local, ...}` literal.
func returnFieldMap(f *ast.File) map[string]string {
	out := map[string]string{}
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "NewMetrics" {
			continue
		}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			cl, ok := n.(*ast.CompositeLit)
			if !ok {
				return true
			}
			for _, elt := range cl.Elts {
				kv, ok := elt.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				key, ok := kv.Key.(*ast.Ident)
				if !ok {
					continue
				}
				if val, ok := kv.Value.(*ast.Ident); ok {
					out[val.Name] = key.Name
				}
			}
			return true
		})
	}
	return out
}

// middlewareInstrument extracts the package-level instrument declared in
// active_requests.go (a var initialized by a func literal), plus the var name
// for call-site scanning.
func middlewareInstrument(f *ast.File) (instrument, string, token.Pos, error) {
	var ins instrument
	var name string
	var pos token.Pos
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || len(vs.Names) != 1 || len(vs.Values) != 1 {
				continue
			}
			name = vs.Names[0].Name
			pos = vs.Pos()
			ast.Inspect(vs.Values[0], func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok || len(call.Args) == 0 {
					return true
				}
				sel, ok := call.Fun.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				kind, known := kindByConstructor[sel.Sel.Name]
				if !known {
					return true
				}
				if nm, ok := stringLiteral(call.Args[0]); ok {
					ins = parseOptions(call.Args[1:], nil, instrument{Name: nm, Kind: kind})
				}
				return false
			})
		}
	}
	if ins.Name == "" {
		return ins, "", pos, fmt.Errorf("no instrument found in active_requests.go")
	}
	return ins, name, pos, nil
}

type adapterInfo struct {
	label      string
	attributes []string
}

// parseAdapters maps Metrics-struct field names to their adapter method
// (`type.method`) and the attribute keys the method sets.
func parseAdapters(f *ast.File) map[string]adapterInfo {
	out := map[string]adapterInfo{}
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 {
			continue
		}
		recv := receiverTypeName(fn.Recv.List[0].Type)
		if recv == "" {
			continue
		}
		field := ""
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			sel, ok := n.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			if sel.Sel.Name != "Add" && sel.Sel.Name != "Record" {
				return true
			}
			if x, ok := sel.X.(*ast.SelectorExpr); ok {
				field = x.Sel.Name
				return false
			}
			return true
		})
		if field == "" {
			continue
		}
		info := adapterInfo{label: recv + "." + fn.Name.Name}
		ast.Inspect(fn.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || len(call.Args) == 0 {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok || sel.Sel.Name != "String" {
				return true
			}
			if pkg, ok := sel.X.(*ast.Ident); ok && pkg.Name == "attribute" {
				if key, ok := stringLiteral(call.Args[0]); ok {
					info.attributes = append(info.attributes, key)
				}
			}
			return true
		})
		sort.Strings(info.attributes)
		out[field] = info
	}
	return out
}

func receiverTypeName(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return receiverTypeName(t.X)
	}
	return ""
}

func stringLiteral(expr ast.Expr) (string, bool) {
	bl, ok := expr.(*ast.BasicLit)
	if !ok || bl.Kind != token.STRING {
		return "", false
	}
	v, err := strconv.Unquote(bl.Value)
	if err != nil {
		return "", false
	}
	return v, true
}

// --- call-site scanning ----------------------------------------------------

func varCallSites(fset *token.FileSet, f *ast.File, varName, repoRelFile string) []string {
	var sites []string
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
			if x, ok := sel.X.(*ast.Ident); ok && x.Name == varName {
				sites = append(sites, repoRelFile+":"+strconv.Itoa(fset.Position(call.Lparen).Line))
			}
		}
		return true
	})
	return sites
}

// scanCallSites loads every package under internal/ and records call
// expressions whose method name matches an adapter method. packages.Load
// already excludes _test.go files from the compiled syntax.
func scanCallSites(backendDir string, byMethod map[string]*instrument) error {
	cfg := &packages.Config{
		Dir:  backendDir,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax,
	}
	pkgs, err := packages.Load(cfg, "markpost/internal/...")
	if err != nil {
		return err
	}
	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			return pkg.Errors[0]
		}
		for _, file := range pkg.Syntax {
			path := pkg.Fset.Position(file.Pos()).Filename
			if strings.HasSuffix(path, "_test.go") {
				continue
			}
			ast.Inspect(file, func(n ast.Node) bool {
				call, ok := n.(*ast.CallExpr)
				if !ok {
					return true
				}
				sel, ok := call.Fun.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				if target, ok := byMethod[sel.Sel.Name]; ok {
					target.CallSites = append(target.CallSites,
						relToRepo(backendDir, path)+":"+strconv.Itoa(pkg.Fset.Position(call.Lparen).Line))
				}
				return true
			})
		}
	}
	return nil
}

// --- version anchoring -----------------------------------------------------

var goModVerRe = regexp.MustCompile(`^\s+(\S+)\s+(v\S+)`)

func readDepVersions(backendDir string) (otelgin, runtimeVer string, err error) {
	data, err := os.ReadFile(filepath.Join(backendDir, "go.mod"))
	if err != nil {
		return "", "", err
	}
	for _, line := range strings.Split(string(data), "\n") {
		m := goModVerRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		switch m[1] {
		case "go.opentelemetry.io/contrib/instrumentation/github.com/gin-gonic/gin/otelgin":
			otelgin = m[2]
		case "go.opentelemetry.io/contrib/instrumentation/runtime":
			runtimeVer = m[2]
		}
	}
	if otelgin == "" || runtimeVer == "" {
		return "", "", fmt.Errorf("otelgin or contrib runtime not found in go.mod")
	}
	if _, ok := verifiedOtelgin[otelgin]; !ok {
		return "", "", fmt.Errorf("otelgin %s has no verified instrument table in tools/metricsdoc — verify the emitted set against that release and extend verifiedOtelgin", otelgin)
	}
	if _, ok := verifiedRuntime[runtimeVer]; !ok {
		return "", "", fmt.Errorf("contrib runtime %s has no verified instrument table in tools/metricsdoc — verify the emitted set against that release and extend verifiedRuntime", runtimeVer)
	}
	return otelgin, runtimeVer, nil
}

type autoInstrument struct {
	Name       string
	Kind       string
	Unit       string
	Note       string
	AttrNote   string
	Attributes []string
}

// verifiedOtelgin holds the exact automatic server instruments each pinned
// otelgin release emits, verified against that release's source. otelgin
// delegates to the otel semconv httpconv HTTPServer: three histograms per
// request. http.server.active_requests is NOT among them — that instrument is
// markpost's own middleware. Attributes are the MetricAttributes set.
var verifiedOtelgin = map[string][]autoInstrument{
	"v0.69.0": {
		{Name: "http.server.request.duration", Kind: "histogram", Unit: "s", Attributes: otelginAttrs},
		{Name: "http.server.request.body.size", Kind: "histogram", Unit: "By", Attributes: otelginAttrs},
		{Name: "http.server.response.body.size", Kind: "histogram", Unit: "By", Attributes: otelginAttrs},
	},
}

